//if
let one = 1;

if (one <= 1) {
    console.log("one is less then or equal to 1");
}
else {
    console.log("one is greater than 1");
}


//if else
if (one < 1) {
    console.log("one is less then or equal to 1");
}
else if (one === 1) {
    console.log("one is equal to 1");
}
else {
    console.log("one is greater than 1");
}


